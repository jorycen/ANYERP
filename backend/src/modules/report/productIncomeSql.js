function externalAmountSql(alias = 'gp') {
  // Exact deduction saved in the final snapshot, never today's supplier price.
  return `GREATEST(0, ROUND(${alias}.RECEIVABLE_AMOUNT - ${alias}.PRODUCT_PRICING_AMOUNT - ${alias}.PAYMENT_FEE_AMOUNT - ${alias}.VAT_AMOUNT + ${alias}.SUPPLEMENT_AMOUNT - ${alias}.FREIGHT_COST_AMOUNT - ${alias}.GROSS_PROFIT_AMOUNT, 2))`;
}
function externalIncomeSql() {
  const amount = externalAmountSql();
  const valid = `gp.SNAPSHOT_STATUS = 'final' AND gp.FORMULA_VERSION IN ('ORDER_GP_V9_FREIGHT_SEPARATE', 'ORDER_GP_V11_PRODUCT_COST_MODE') AND ${amount} > 0`;
  return `SELECT 'external' AS ENTRY_TYPE, CONCAT('EXT-', o.ORDER_ID) AS ENTRY_ID, CONCAT('EXT-', o.ORDER_NO) AS ENTRY_NO,
      o.ORDER_ID AS SOURCE_ORDER_ID, o.ORDER_NO AS SOURCE_ORDER_NO, s.DISTRIBUTOR_ID, s.REGION_ID, o.STORE_ID,
      o.CREATE_TIME AS BUSINESS_DATE, 0 AS PRODUCT_PRICING_AMOUNT, 0 AS PURCHASE_COST_AMOUNT,
      ${amount} AS GROSS_PROFIT_AMOUNT, 0 AS COST_PENDING_AMOUNT, 'posted' AS STATUS, 'FROZEN_EXTERNAL_FEE' AS FORMULA_VERSION
    FROM T_ORDER_GROSS_PROFIT gp JOIN T_ORDER o ON o.ORDER_ID = gp.ORDER_ID JOIN T_STORE s ON s.STORE_ID = o.STORE_ID
    WHERE o.IS_DELETED = 0 AND ${valid}
    UNION ALL
    SELECT 'external_return', CONCAT('EXT-RET-', r.RETURN_ID), CONCAT('EXT-', r.RETURN_NO), o.ORDER_ID, o.ORDER_NO,
      s.DISTRIBUTOR_ID, s.REGION_ID, o.STORE_ID, r.BUSINESS_DATE, 0, 0,
      -(ROUND(${amount} * LEAST(1, r.CUMULATIVE_RETURNED / NULLIF(o.TOTAL_AMOUNT, 0)), 2) - ROUND(${amount} * LEAST(1, (r.CUMULATIVE_RETURNED - ABS(r.RETURNED_AMOUNT)) / NULLIF(o.TOTAL_AMOUNT, 0)), 2)), 0, 'posted', 'FROZEN_EXTERNAL_FEE_RETURN'
    FROM (SELECT grouped_returns.*, SUM(ABS(RETURNED_AMOUNT)) OVER (PARTITION BY ORDER_ID ORDER BY BUSINESS_DATE, RETURN_ID ROWS UNBOUNDED PRECEDING) CUMULATIVE_RETURNED
      FROM (SELECT RETURN_ID, MAX(RETURN_NO) RETURN_NO, ORDER_ID, MAX(CREATE_TIME) BUSINESS_DATE,
                 SUM(RETURNED_SALES_AMOUNT) RETURNED_AMOUNT FROM T_SALES_RETURN_GROSS_PROFIT GROUP BY RETURN_ID, ORDER_ID) grouped_returns) r
    JOIN T_ORDER o ON o.ORDER_ID = r.ORDER_ID JOIN T_ORDER_GROSS_PROFIT gp ON gp.ORDER_ID = o.ORDER_ID
    JOIN T_STORE s ON s.STORE_ID = o.STORE_ID WHERE o.IS_DELETED = 0 AND o.TOTAL_AMOUNT > 0 AND ${valid}`;
}
function policyIncomeSql() {
  return `SELECT e.ENTRY_TYPE, e.ENTRY_ID, CONCAT('POL-', e.ENTRY_ID) AS ENTRY_NO, e.SOURCE_ORDER_ID, e.SOURCE_ORDER_NO,
    s.DISTRIBUTOR_ID, s.REGION_ID, e.STORE_ID, e.BUSINESS_DATE, 0 AS PRODUCT_PRICING_AMOUNT, 0 AS PURCHASE_COST_AMOUNT,
    e.AMOUNT AS GROSS_PROFIT_AMOUNT, 0 AS COST_PENDING_AMOUNT, 'posted' AS STATUS, 'REBATE_FULL_MATCH_V1' AS FORMULA_VERSION
    FROM T_PRODUCT_PROFIT_INCOME e JOIN T_STORE s ON s.STORE_ID = e.STORE_ID`;
}
function pendingPolicySql() {
  const snapshot = "IF(JSON_VALID(t.REWARD_SNAPSHOT_JSON), t.REWARD_SNAPSHOT_JSON, '{}')";
  return `SELECT CASE WHEN r.RESOURCE_TYPE = 'EDU_SUBSIDY' THEN 'education' ELSE 'manufacturer' END AS ENTRY_TYPE,
      r.SETTLEMENT_ID AS ENTRY_ID, r.SETTLEMENT_NO AS ENTRY_NO, o.ORDER_ID AS SOURCE_ORDER_ID, o.ORDER_NO AS SOURCE_ORDER_NO,
      s.DISTRIBUTOR_ID, s.REGION_ID, s.STORE_ID, r.CREATE_TIME AS BUSINESS_DATE, 0 AS PRODUCT_PRICING_AMOUNT, 0 AS PURCHASE_COST_AMOUNT,
      CASE WHEN r.RESOURCE_TYPE = 'EDU_SUBSIDY' AND r.SOURCE_TYPE IN ('SALE_USE', 'EDU_PRODUCT_REBATE')
        THEN CAST(JSON_UNQUOTE(JSON_EXTRACT(${snapshot}, '$.productAmount')) AS DECIMAL(12,2)) ELSE r.AMOUNT END AS GROSS_PROFIT_AMOUNT,
      0 AS COST_PENDING_AMOUNT, 'policy_pending' AS STATUS, 'REBATE_WAIT_FULL_MATCH' AS FORMULA_VERSION
    FROM T_RESOURCE_SETTLEMENT r
    LEFT JOIN T_REBATE_ESTIMATE estimate ON estimate.ESTIMATE_ID = r.SOURCE_ID AND r.SOURCE_TYPE = 'MANUFACTURER_REBATE'
    LEFT JOIN T_RESOURCE_RIGHT_CHANGE_ORDER t ON t.CHANGE_ID = REPLACE(r.SOURCE_ID, 'PRICE_CLAIM_', '')
    LEFT JOIN T_ORDER o ON o.ORDER_ID = COALESCE(estimate.SALES_ORDER_ID, t.RELATED_SALE_ORDER_ID)
    LEFT JOIN T_PRODUCT_SN sn ON sn.SN_ID = r.SN_ID
    JOIN T_STORE s ON s.STORE_ID = COALESCE(o.STORE_ID, sn.STORE_ID)
    WHERE r.STATUS IN ('PENDING', 'PARTIALLY_SETTLED') AND r.AMOUNT > 0
      AND (r.RESOURCE_TYPE = 'MANUFACTURER_REBATE' OR r.SOURCE_TYPE = 'MANUFACTURER_REBATE'
        OR r.SOURCE_TYPE = 'EDU_PRODUCT_REBATE'
        OR (r.RESOURCE_TYPE = 'EDU_SUBSIDY' AND r.SOURCE_TYPE = 'SALE_USE'
          AND JSON_EXTRACT(${snapshot}, '$.accountingVersion') = 2))`;
}
