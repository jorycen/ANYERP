const test = require('node:test');
const assert = require('node:assert/strict');
test('reward receipt, stock holds, profit, races, rollback and expiry', { skip: process.env.RUN_CUSTOMER_DB_TESTS !== 'true' }, async () => {
  const config = require('../src/config');
  const mysql = require('mysql2/promise');
  const source = config.database.database;
  if (!/^[a-zA-Z0-9_-]+$/.test(source)) throw new Error('Invalid database');
  const name = `reward_test_${Date.now()}_${process.pid}`;
  const control = await mysql.createConnection({ host: config.database.host, port: config.database.port, user: config.database.username, password: config.database.password });
  let sequelize;
  try {
    await control.query(`CREATE DATABASE \`${name}\` CHARACTER SET utf8mb4`);
    for (const table of ['T_STORE','T_STAFF','T_DISTRIBUTOR','T_PRODUCT','T_PRODUCT_SN','T_INVENTORY','T_DICT_PAYMENT_METHOD','T_DICT_PAYMENT_METHOD_STORE','T_SETTLEMENT_ACCOUNT','T_SETTLEMENT_ACCOUNT_TRANSACTION','T_OUTBOUND','T_OUTBOUND_ITEM','T_INBOUND','T_INBOUND_ITEM','T_NON_PURCHASE_RECEIPT','T_INVENTORY_BATCH_APPLICATION','T_INVENTORY_BATCH_APPLICATION_ITEM']) {
      await control.query(`CREATE TABLE \`${name}\`.\`${table}\` LIKE \`${source}\`.\`${table}\``);
    }
    config.database.database = name;
    process.env.CUSTOMER_OPS_ENABLED = 'true';
    process.env.CUSTOMER_TOKEN_SECRET = require('crypto').randomBytes(32).toString('hex');
    sequelize = require('../src/config/database').sequelize;
    const DB = require('../src/models'), M = require('../src/modules/customerOps/models');
    const V = require('../src/modules/customerOps/service'), F = require('../src/modules/customerOps/fulfillment'), S = require('../src/modules/customerOps/security');
    for (const model of Object.values(M)) await model.sync();
    await DB.BusinessActionLog.sync();
    await require('../scripts/migrate-reward-fulfillment').migrate(true);
    await require('../scripts/migrate-reward-fulfillment').migrate(true);
    await DB.Distributor.create({distributor_id:'d',name:'dealer',status:1,is_deleted:0});
    await DB.Store.bulkCreate([{store_id:'a',distributor_id:'d',name:'A',status:1,is_deleted:0},{store_id:'b',distributor_id:'d',name:'B',status:1,is_deleted:0}]);
    await DB.Staff.create({staff_id:1,distributor_id:'d',store_id:'a',name:'Redeemer',phone:'13000000001'});
    await DB.Product.create({product_id:'p',product_code:'p',name:'Gift',need_sn:0,is_deleted:0});
    await DB.Inventory.create({inventory_id:'inv',product_id:'p',store_id:'a',normal_qty:2,regular_qty:2,location_id:''});
    await DB.SettlementAccount.create({account_id:'fund',account_name:'Fund',account_type:'FUND',distributor_id:'d',status:1});
    await DB.PaymentMethod.create({method_id:'cash',name:'Cash',code:'CASH',settlement_account_id:'fund',is_global:1,status:1});
    await sequelize.query("INSERT INTO T_INBOUND (INBOUND_ID, INBOUND_NO, STORE_ID, STATUS, SOURCE_TYPE, CREATE_TIME) VALUES ('in','in','a','completed','GIFT',NOW())");
    await sequelize.query("INSERT INTO T_INBOUND_ITEM (INBOUND_ID, PRODUCT_ID, UNIT_PRICE, QUANTITY) VALUES ('in','p',12,2)");
    const member = await M.Member.create({phone:'13000000000'});
    await M.Account.create({member_id:member.id,distributor_id:'d',balance:'10000'});
    const reward = await M.Reward.create({distributor_id:'d',name:'Gift',kind:'gift',product_id:'p',units_per_reward:1,points:'10',stock:null,cash_required:'39.00',valid_days:30,on_sale:true});
    await M.RewardStore.bulkCreate([{reward_id:reward.id,store_id:'a'},{reward_id:reward.id,store_id:'b'}]);
    await assert.rejects(V.exchange(member,reward.id,'missing_store_key','10','39'), /领取门店/);
    await assert.rejects(V.exchange(member,reward.id,'empty_store_key_1','10','39','b'), /库存不足/);
    const attempts = await Promise.allSettled([1,2,3].map(n => V.exchange(member,reward.id,`concurrent_key_${n}`,'10','39','a')));
    assert.equal(attempts.filter(r=>r.status==='fulfilled').length,2);
    const exchanges = await M.Exchange.findAll();
    assert.equal(await F.availability(reward,'a'),0);
    assert.equal((await F.catalogueStock([reward],['a','b'])).get(reward.id).get('a'),0);
    assert.equal((await DB.Inventory.findByPk('inv')).normal_qty,2);
    await assert.rejects(sequelize.query("UPDATE T_INVENTORY SET NORMAL_QTY=1, REGULAR_QTY=1 WHERE INVENTORY_ID='inv'"), /reserved/);
    await assert.rejects(sequelize.query("DELETE FROM T_INVENTORY WHERE INVENTORY_ID='inv'"), /reserved/);
    const user={staffId:1,roles:['staff'],accessibleStoreIds:['a'],accessibleDistributorIds:['d']};
    const first=exchanges[0], code=S.token('redeem',first.id);
    await assert.rejects(V.redeem(code,'b',{...user,accessibleStoreIds:['b']},true,first.id,{}), /不适用/);
    await assert.rejects(V.redeem(code,'a',user,true,first.id,{cash_confirmed:true,cash_received:'38',payment_method_id:'cash'}), /现金补差/);
    await assert.rejects(V.redeem(code,'a',user,true,first.id,{cash_confirmed:true,cash_received:'39',payment_method_id:'missing'}), /收款方式/);
    assert.equal(await DB.SettlementAccountTransaction.count(),0);
    assert.equal((await V.redeem(code,'a',user,false)).paymentMethods[0].account_id,'fund');
    const evidence={cash_confirmed:true,cash_received:'39',payment_method_id:'cash'};
    const results=await Promise.all([V.redeem(code,'a',user,true,first.id,evidence),V.redeem(code,'a',user,true,first.id,evidence)]);
    assert.equal(results.filter(r=>r.alreadyRedeemed).length,1);
    assert.equal(await DB.SettlementAccountTransaction.count(),1);
    assert.equal(await DB.Outbound.count(),1);
    const redemption=await M.Redemption.findOne();
    assert.equal(redemption.sales_profit,'19.50');
    assert.equal(redemption.cost_amount,'12.00');
    assert.equal(redemption.operations_profit,'7.50');
    assert.equal((await DB.Inventory.findByPk('inv')).normal_qty,1);
    const range={startAt:new Date(Date.now()-86400000),endAt:new Date(Date.now()+86400000)};
    const profits=require('../src/modules/customerOps/profitEvents');
    assert.equal((await profits.events({storeIds:['a']},range))[0].base_gross_profit,19.5);
    assert.equal((await profits.operations({storeIds:['a']},range)).operationsGrossProfit,7.5);
    assert.equal((await profits.events({storeIds:['b']},range)).length,0);
    await M.Reservation.update({expires_at:new Date(Date.now()-60000)},{where:{exchange_id:exchanges[1].id}});
    await M.Exchange.update({expires_at:new Date(Date.now()-60000)},{where:{id:exchanges[1].id}});
    assert.equal(await F.availability(reward,'a'),1);
    assert.equal((await F.catalogueStock([reward],['a','b'])).get(reward.id).get('a'),1);
    await assert.rejects(V.redeem(S.token('redeem',exchanges[1].id),'a',user,true,exchanges[1].id,evidence), /失效/);
    await reward.update({cash_required:'0.00'});
    const free=await V.exchange(member,reward.id,'free_gift_key_001','10','0','a');
    await V.redeem(S.token('redeem',free.id),'a',user,true,free.id,{});
    const freeReceipt=await M.Redemption.findOne({where:{exchange_id:free.id}});
    assert.equal(freeReceipt.sales_profit,'0.00');
    assert.equal(freeReceipt.operations_profit,'-12.00');
    assert.equal(await DB.SettlementAccountTransaction.count(),1);
    assert.equal((await DB.Inventory.findByPk('inv')).normal_qty,0);
    // If cost cannot be established, even an already-created receipt is rolled back.
    await DB.Product.create({product_id:'unknown',product_code:'unknown',name:'Unknown cost',need_sn:0,is_deleted:0});
    await DB.Inventory.create({inventory_id:'unknown-inv',product_id:'unknown',store_id:'a',location_id:'',normal_qty:1});
    await reward.update({product_id:'unknown',cash_required:'0.01'});
    const unknown=await V.exchange(member,reward.id,'unknown_cost_key_1','10','0.01','a');
    await assert.rejects(V.redeem(S.token('redeem',unknown.id),'a',user,true,unknown.id,{...evidence,cash_received:'0.01'}), /成本/);
    assert.equal(await DB.SettlementAccountTransaction.count(),1);
    assert.equal((await M.Exchange.findByPk(unknown.id)).status,'pending');
    assert.equal((await DB.Inventory.findByPk('unknown-inv')).normal_qty,1);
    assert.equal((await M.Reservation.findOne({where:{exchange_id:unknown.id}})).status,'reserved');
    // Serialized gifts use the scanned unit's actual purchase cost and persist traceable SN issue lines.
    await DB.Product.create({product_id:'serial',product_code:'serial',name:'SN gift',need_sn:1,is_deleted:0});
    await DB.Inventory.create({inventory_id:'serial-inv',product_id:'serial',store_id:'a',location_id:'',normal_qty:1});
    await DB.ProductSn.create({sn_id:'sn',product_id:'serial',sn_code:'SN-GIFT-001',store_id:'a',location_id:'',inventory_type:'normal_qty',status:'in_stock',inbound_price:'10.00',is_deleted:0});
    await reward.update({product_id:'serial',cash_required:'0.01'});
    const serial=await V.exchange(member,reward.id,'serial_gift_key01','10','0.01','a');
    await assert.rejects(V.redeem(S.token('redeem',serial.id),'a',user,true,serial.id,{...evidence,cash_received:'0.01',sn_codes:['wrong']}), /SN/);
    await V.redeem(S.token('redeem',serial.id),'a',user,true,serial.id,{...evidence,cash_received:'0.01',sn_codes:['SN-GIFT-001']});
    const serialReceipt=await M.Redemption.findOne({where:{exchange_id:serial.id}});
    assert.equal(serialReceipt.sales_profit,'0.00');
    assert.equal(serialReceipt.operations_profit,'-9.99');
    assert.equal((await DB.ProductSn.findByPk('sn')).status,'sold');
    assert.equal((await DB.Inventory.findByPk('serial-inv')).normal_qty,0);
    assert.equal(await DB.SettlementAccountTransaction.count(),2);
    assert.equal((await DB.OutboundItem.findOne({where:{outbound_id:serialReceipt.outbound_id}})).sn_code,'SN-GIFT-001');
  } finally {
    if (sequelize) await sequelize.close();
    await control.query(`DROP DATABASE IF EXISTS \`${name}\``);
    await control.end();
  }
});
