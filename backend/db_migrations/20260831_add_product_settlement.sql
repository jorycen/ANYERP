-- 产品端结算单及销售退货负向调整。
-- 产品端毛利只按产品定价/结算价与实际采购成本计算；厂家返利、价保等政策不写入本组表。
CREATE TABLE IF NOT EXISTS T_PRODUCT_SETTLEMENT_ORDER (
  SETTLEMENT_ID VARCHAR(32) NOT NULL,
  SETTLEMENT_NO VARCHAR(64) NOT NULL,
  SOURCE_ORDER_ID VARCHAR(32) NOT NULL,
  SOURCE_ORDER_NO VARCHAR(64) NOT NULL,
  DISTRIBUTOR_ID VARCHAR(32),
  REGION_ID VARCHAR(32),
  STORE_ID VARCHAR(32) NOT NULL,
  BUSINESS_DATE DATETIME NOT NULL,
  PRODUCT_PRICING_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  PURCHASE_COST_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  GROSS_PROFIT_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  COST_PENDING_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  STATUS VARCHAR(32) NOT NULL DEFAULT 'posted',
  FORMULA_VERSION VARCHAR(32) NOT NULL,
  CREATE_USER VARCHAR(64),
  CREATE_TIME DATETIME DEFAULT CURRENT_TIMESTAMP,
  UPDATE_TIME DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (SETTLEMENT_ID),
  UNIQUE KEY uk_product_settlement_source_order (SOURCE_ORDER_ID),
  UNIQUE KEY uk_product_settlement_no (SETTLEMENT_NO),
  KEY idx_product_settlement_scope_date (STORE_ID, BUSINESS_DATE, STATUS),
  KEY idx_product_settlement_distributor (DISTRIBUTOR_ID, BUSINESS_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='产品端销售结算单';

CREATE TABLE IF NOT EXISTS T_PRODUCT_SETTLEMENT_ITEM (
  SETTLEMENT_ITEM_ID BIGINT NOT NULL AUTO_INCREMENT,
  SETTLEMENT_ID VARCHAR(32) NOT NULL,
  SOURCE_ORDER_ITEM_ID BIGINT NOT NULL,
  PRODUCT_ID VARCHAR(32),
  PRODUCT_NAME VARCHAR(255),
  PN_CODE VARCHAR(64),
  SN_ID VARCHAR(32),
  SN_CODE VARCHAR(128),
  QUANTITY INT NOT NULL DEFAULT 1,
  PRODUCT_UNIT_PRICE DECIMAL(12,2) NOT NULL DEFAULT 0,
  PRODUCT_PRICE_SOURCE VARCHAR(64),
  PURCHASE_UNIT_COST DECIMAL(12,2) NOT NULL DEFAULT 0,
  PURCHASE_COST_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  COST_METHOD VARCHAR(64) NOT NULL,
  COST_SOURCE VARCHAR(128),
  COST_STATUS VARCHAR(32) NOT NULL DEFAULT 'ready',
  GROSS_PROFIT_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  CREATE_TIME DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (SETTLEMENT_ITEM_ID),
  KEY idx_product_settlement_item_order (SETTLEMENT_ID),
  KEY idx_product_settlement_item_source (SOURCE_ORDER_ITEM_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='产品端销售结算明细';

CREATE TABLE IF NOT EXISTS T_PRODUCT_SETTLEMENT_ADJUSTMENT (
  ADJUSTMENT_ID VARCHAR(32) NOT NULL,
  ADJUSTMENT_NO VARCHAR(64) NOT NULL,
  SOURCE_RETURN_ID VARCHAR(32) NOT NULL,
  SOURCE_RETURN_NO VARCHAR(64) NOT NULL,
  SOURCE_ORDER_ID VARCHAR(32) NOT NULL,
  SOURCE_ORDER_NO VARCHAR(64) NOT NULL,
  DISTRIBUTOR_ID VARCHAR(32),
  REGION_ID VARCHAR(32),
  STORE_ID VARCHAR(32) NOT NULL,
  BUSINESS_DATE DATETIME NOT NULL,
  PRODUCT_PRICING_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  PURCHASE_COST_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  GROSS_PROFIT_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  COST_PENDING_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  STATUS VARCHAR(32) NOT NULL DEFAULT 'posted',
  FORMULA_VERSION VARCHAR(32) NOT NULL,
  CREATE_USER VARCHAR(64),
  CREATE_TIME DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ADJUSTMENT_ID),
  UNIQUE KEY uk_product_settlement_return (SOURCE_RETURN_ID),
  UNIQUE KEY uk_product_settlement_adjustment_no (ADJUSTMENT_NO),
  KEY idx_product_settlement_adjustment_scope (STORE_ID, BUSINESS_DATE, STATUS),
  KEY idx_product_settlement_adjustment_order (SOURCE_ORDER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='产品端销售退货负向调整单';

CREATE TABLE IF NOT EXISTS T_PRODUCT_SETTLEMENT_ADJUSTMENT_ITEM (
  ADJUSTMENT_ITEM_ID BIGINT NOT NULL AUTO_INCREMENT,
  ADJUSTMENT_ID VARCHAR(32) NOT NULL,
  SOURCE_RETURN_ITEM_ID BIGINT NOT NULL,
  SOURCE_ORDER_ITEM_ID BIGINT NOT NULL,
  PRODUCT_ID VARCHAR(32),
  PRODUCT_NAME VARCHAR(255),
  PN_CODE VARCHAR(64),
  SN_ID VARCHAR(32),
  SN_CODE VARCHAR(128),
  QUANTITY INT NOT NULL DEFAULT 1,
  PRODUCT_UNIT_PRICE DECIMAL(12,2) NOT NULL DEFAULT 0,
  PRODUCT_PRICING_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  PURCHASE_UNIT_COST DECIMAL(12,2) NOT NULL DEFAULT 0,
  PURCHASE_COST_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  COST_METHOD VARCHAR(64) NOT NULL,
  COST_STATUS VARCHAR(32) NOT NULL DEFAULT 'ready',
  GROSS_PROFIT_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  CREATE_TIME DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ADJUSTMENT_ITEM_ID),
  KEY idx_product_settlement_adjustment_item_order (ADJUSTMENT_ID),
  KEY idx_product_settlement_adjustment_item_source (SOURCE_ORDER_ITEM_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='产品端销售退货负向调整明细';
