CREATE TABLE IF NOT EXISTS T_PRODUCT_PROFIT_INCOME (
  ENTRY_ID VARCHAR(32) NOT NULL PRIMARY KEY,
  ENTRY_KEY VARCHAR(160) NOT NULL,
  ENTRY_TYPE VARCHAR(32) NOT NULL,
  SETTLEMENT_ID VARCHAR(32) NOT NULL,
  SOURCE_ORDER_ID VARCHAR(32),
  SOURCE_ORDER_NO VARCHAR(64),
  STORE_ID VARCHAR(32) NOT NULL,
  AMOUNT DECIMAL(12,2) NOT NULL,
  BUSINESS_DATE DATETIME NOT NULL,
  REVERSES_ENTRY_ID VARCHAR(32),
  DETAIL_JSON JSON,
  CREATE_USER VARCHAR(64),
  UNIQUE KEY UK_PRODUCT_INCOME_KEY (ENTRY_KEY),
  UNIQUE KEY UK_PRODUCT_INCOME_REVERSE (REVERSES_ENTRY_ID),
  KEY IDX_PRODUCT_INCOME_PERIOD (STORE_ID, BUSINESS_DATE),
  KEY IDX_PRODUCT_INCOME_SETTLEMENT (SETTLEMENT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
