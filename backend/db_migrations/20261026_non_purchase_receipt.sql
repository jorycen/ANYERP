CREATE TABLE IF NOT EXISTS T_NON_PURCHASE_RECEIPT (
 RECEIPT_ID VARCHAR(32) NOT NULL PRIMARY KEY,
 RECEIPT_NO VARCHAR(64) NOT NULL UNIQUE,
 REQUEST_KEY VARCHAR(64) NOT NULL UNIQUE,
 SOURCE_TYPE VARCHAR(32) NOT NULL,
 ORDER_ID VARCHAR(32) NULL,
 ORDER_NO VARCHAR(64) NULL,
 STORE_ID VARCHAR(32) NOT NULL,
 DISTRIBUTOR_ID VARCHAR(32) NULL,
 APPLICANT_STAFF_ID BIGINT NOT NULL,
 APPLICANT_NAME VARCHAR(64) NOT NULL,
 REASON VARCHAR(1000) NOT NULL,
 PAYLOAD_JSON LONGTEXT NOT NULL,
 STATUS VARCHAR(32) NOT NULL DEFAULT 'pending',
 TOTAL_AMOUNT DECIMAL(12,2) NULL,
 INBOUND_ID VARCHAR(32) NULL,
 ADJUSTMENT_ID VARCHAR(32) NULL,
 REVIEWER_NAME VARCHAR(64) NULL,
 REVIEW_TIME DATETIME NULL,
 CREATE_TIME DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UPDATE_TIME DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX IDX_NPR_ORDER (ORDER_ID, STATUS),
 INDEX IDX_NPR_STORE (STORE_ID, STATUS),
 UNIQUE KEY UK_NPR_INBOUND (INBOUND_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
