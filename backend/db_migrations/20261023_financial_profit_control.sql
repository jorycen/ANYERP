CREATE TABLE IF NOT EXISTS T_FINANCIAL_PROFIT_REVIEW (
  EVENT_KEY VARCHAR(100) NOT NULL PRIMARY KEY,
  STORE_ID VARCHAR(32) NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  REVISION INT NOT NULL,
  SOURCE_HASH VARCHAR(64) NOT NULL,
  REVIEW_JSON LONGTEXT NOT NULL,
  UPDATE_TIME DATETIME(3) NOT NULL,
  KEY IDX_FINANCIAL_REVIEW_STORE_DATE (STORE_ID, BUSINESS_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS T_FINANCIAL_PROFIT_PERIOD (
  MONTH_KEY VARCHAR(7) NOT NULL PRIMARY KEY,
  SNAPSHOT_JSON LONGTEXT NOT NULL,
  SNAPSHOT_HASH VARCHAR(64) NOT NULL,
  CLOSED_BY VARCHAR(64) NOT NULL,
  CLOSED_AT DATETIME(3) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS T_FINANCIAL_PROFIT_ADJUSTMENT (
  ADJUSTMENT_ID VARCHAR(32) NOT NULL PRIMARY KEY,
  REQUEST_KEY VARCHAR(64) NOT NULL,
  STORE_ID VARCHAR(32) NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  SOURCE_EVENT_KEY VARCHAR(100) NOT NULL,
  DETAIL_JSON LONGTEXT NOT NULL,
  CREATE_USER VARCHAR(64) NOT NULL,
  CREATE_TIME DATETIME(3) NOT NULL,
  UNIQUE KEY UK_FINANCIAL_ADJUSTMENT_REQUEST (REQUEST_KEY),
  KEY IDX_FINANCIAL_ADJUSTMENT_DATE (STORE_ID, BUSINESS_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
